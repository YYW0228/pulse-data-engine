def main() -> int:
    ap = argparse.ArgumentParser(description="Flywheel 零 LLM 聚类")
    ap.add_argument("--review", action="store_true", help="只刷新 REVIEW_QUEUE (不重聚类)")
    ap.add_argument("--example", action="store_true", help="生成样例失败后退出")
    args = ap.parse_args()

    now = datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds")

    if args.example:
        gen_examples()
        return 0

    failures = load_failures()
    print(f"扫描失败痕迹: {len(failures)} 条")

    if args.review:
        patterns = [json.loads(f.read_text()) for f in sorted(CANDIDATES.glob("*.json"))] if CANDIDATES.exists() else []
    else:
        clusters = cluster(failures)
        patterns = build_patterns(clusters)
        write_candidates(patterns)
        print(f"聚类结果: {len(clusters)} 簇 → {len(patterns)} 个 pattern (≥{MIN_PATTERN_COUNT} 条)")

    REVIEW_QUEUE.write_text(render_queue(patterns, now), encoding="utf-8")
    print(f"REVIEW_QUEUE.md 已更新: {len(patterns)} 个待审 pattern")
    return 0


if __name__ == "__main__":
    sys.exit(main())
